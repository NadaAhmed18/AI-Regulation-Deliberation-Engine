    # Smoke test: python -m src.discussion.opinion_state   (from backend/ root)
    tracker = DiscussionOpinionTracker(topic="Classifying Open Source Models under the EU AI Act")

    # Note: "Pro-Regulation" here is Elena's static persona STANCE
    # (personas/persona_a.yaml) — it never appears in this module. What we
    # track below is her OPINION on this one topic, which starts narrower
    # and more qualified than her general stance.
    tracker.record_initial(
        persona_id="persona_a",
        agent_name="Dr. Elena Kovac",
        opinion_text="Open-source models should not get a blanket exemption from high-risk obligations.",
        score=0.8,
    )
    tracker.record_round(
        persona_id="persona_a",
        agent_name="Dr. Elena Kovac",
        round_number=1,
        opinion_text="I can accept a narrower carve-out for non-commercial research releases specifically.",
        score=0.6,
    )

    elena_state = tracker.get("persona_a")
    print(f"Initial:   {elena_state.initial().opinion_text}")
    print(f"Latest:    {elena_state.latest().opinion_text}")
    print(f"Net shift: {elena_state.net_shift()}  (positive score = more pro-regulation)")

    print("\n--- Full tracker summary (JSON-ready) ---")
    import json
    print(json.dumps(tracker.summary(), indent=2))

"""
OPINION STATE — Week 3 Discussion Engine

Purpose:
    Track how each agent's opinion evolves during ONE discussion about ONE
    topic, kept explicitly separate from the persona's static `stance`.

Why this needs to be its own module (not just reuse the persona dict):
    A persona's `stance` field (from `personas/*.yaml`, loaded via
    `src.utils.yaml_loader.load_persona`) describes who the stakeholder is
    in general — e.g. Elena is "Pro-Regulation" as a standing worldview.
    That does not change between discussions and is not what Week 3 asks
    the system to track.

    What Week 3 requires is different: THIS agent's position on THIS
    specific topic, at multiple points in THIS specific discussion —
        Initial opinion -> after Round 1 -> after Round 2 -> after Round 3
    A pro-regulation persona can still hold a moderate initial opinion on
    one narrow topic and a strong one on another; the same persona reused
    across two different discussions produces two independent opinion
    histories. Storing that inside the persona dict itself would leak
    per-discussion state into what is supposed to be reusable, static
    configuration — the exact bug this module exists to avoid.

Score is optional and uninterpreted here:
    `score` is stored as given (e.g. -1.0..+1.0, "pro-regulation" vs
    "pro-innovation", or omitted entirely). This module does not compute
    scores — it just records whatever the discussion engine passes in.
    Computing a stance score is a separate concern (see
    `src/research/opinion_shift_prototype.py` for one candidate approach)
    and could change without this module changing.
"""

from dataclasses import dataclass, field
from datetime import datetime, timezone
from typing import Any, Optional


@dataclass
class OpinionSnapshot:
    """One recorded opinion at a single point in the discussion.

    Attributes:
        round_number: 0 for the initial (pre-discussion) opinion, then 1,
            2, 3, ... for each discussion round after which the opinion
            was recorded.
        opinion_text: The agent's own words, as generated by the LLM
            (e.g. output of `generate_initial_opinion()` for round 0, or a
            round-end opinion summary for later rounds).
        score: Optional numeric stance score for this snapshot. Meaning
            and range are defined by whatever scoring method the caller
            uses (see module docstring); `None` if no scorer was applied.
        recorded_at: UTC timestamp of when this snapshot was recorded.
    """

    round_number: int
    opinion_text: str
    score: Optional[float] = None
    recorded_at: str = field(default_factory=lambda: datetime.now(timezone.utc).isoformat())

    def to_dict(self) -> dict[str, Any]:
        return {
            "round_number": self.round_number,
            "opinion_text": self.opinion_text,
            "score": self.score,
            "recorded_at": self.recorded_at,
        }


@dataclass
class OpinionState:
    """The full opinion history of ONE agent across ONE discussion.

    Attributes:
        persona_id: The stable identifier from the persona pool (e.g.
            "persona_a") — see `src.discussion.persona_pool`. Used to join
            this opinion history back to the persona that produced it
            without duplicating the persona's static fields here.
        agent_name: Display name at the time of recording (e.g.
            "Dr. Elena Kovac"), copied in for convenience so this object
            is self-describing without a pool lookup.
        topic: The discussion topic this opinion history applies to. The
            same `persona_id` used in a different discussion (different
            topic) gets its own, independent `OpinionState`.
        snapshots: Chronological list of `OpinionSnapshot`s, starting with
            round 0 (initial opinion) once `record_initial()` is called.
    """

    persona_id: str
    agent_name: str
    topic: str
    snapshots: list[OpinionSnapshot] = field(default_factory=list)

    def record_initial(self, opinion_text: str, score: Optional[float] = None) -> None:
        """Record the agent's pre-discussion opinion (round 0).

        Raises:
            ValueError: If an initial opinion was already recorded for
                this agent/topic — call `record_round()` for subsequent
                updates instead.
        """
        if any(s.round_number == 0 for s in self.snapshots):
            raise ValueError(
                f"Initial opinion already recorded for '{self.agent_name}' "
                f"on topic '{self.topic}'. Use record_round() for updates."
            )
        self.snapshots.append(OpinionSnapshot(round_number=0, opinion_text=opinion_text, score=score))

    def record_round(self, round_number: int, opinion_text: str, score: Optional[float] = None) -> None:
        """Record the agent's opinion after a specific discussion round.

        Args:
            round_number: Must be 1 or greater (round 0 is reserved for
                `record_initial()`), and must not already have a snapshot
                recorded for this agent/topic.

        Raises:
            ValueError: If `round_number` is not a positive integer, or a
                snapshot for that round already exists.
        """
        if round_number < 1:
            raise ValueError(
                f"round_number must be >= 1 (got {round_number}); use "
                f"record_initial() for the pre-discussion opinion."
            )
        if any(s.round_number == round_number for s in self.snapshots):
            raise ValueError(
                f"Round {round_number} opinion already recorded for "
                f"'{self.agent_name}' on topic '{self.topic}'."
            )
        self.snapshots.append(
            OpinionSnapshot(round_number=round_number, opinion_text=opinion_text, score=score)
        )

    def initial(self) -> Optional[OpinionSnapshot]:
        """Return the round-0 snapshot, or `None` if not yet recorded."""
        return next((s for s in self.snapshots if s.round_number == 0), None)

    def latest(self) -> Optional[OpinionSnapshot]:
        """Return the most recent snapshot (highest round_number), or `None`."""
        if not self.snapshots:
            return None
        return max(self.snapshots, key=lambda s: s.round_number)

    def net_shift(self) -> Optional[float]:
        """
        Return `latest().score - initial().score`, or `None` if either
        snapshot is missing or either lacks a numeric score.

        A positive/negative sign only means "score increased/decreased"
        under whatever convention the caller's scorer uses — this method
        does not interpret direction (e.g. "toward regulation").
        """
        first, last = self.initial(), self.latest()
        if first is None or last is None or first.score is None or last.score is None:
            return None
        return last.score - first.score

    def to_dict(self) -> dict[str, Any]:
        """Serialize to a JSON-ready dict for discussion persistence."""
        return {
            "persona_id": self.persona_id,
            "agent_name": self.agent_name,
            "topic": self.topic,
            "snapshots": [s.to_dict() for s in self.snapshots],
        }


class DiscussionOpinionTracker:
    """
    Convenience container holding one `OpinionState` per participating
    agent for a single discussion. This is the object the discussion
    engine actually holds onto — it hides the per-agent bookkeeping so
    the orchestration loop can just call `record_initial(...)` /
    `record_round(...)` with a `persona_id` and not worry about creating
    `OpinionState` objects itself.
    """

    def __init__(self, topic: str):
        self.topic = topic
        self._states: dict[str, OpinionState] = {}

    def _get_or_create(self, persona_id: str, agent_name: str) -> OpinionState:
        if persona_id not in self._states:
            self._states[persona_id] = OpinionState(
                persona_id=persona_id, agent_name=agent_name, topic=self.topic
            )
        return self._states[persona_id]

    def record_initial(
        self, persona_id: str, agent_name: str, opinion_text: str, score: Optional[float] = None
    ) -> None:
        self._get_or_create(persona_id, agent_name).record_initial(opinion_text, score)

    def record_round(
        self,
        persona_id: str,
        agent_name: str,
        round_number: int,
        opinion_text: str,
        score: Optional[float] = None,
    ) -> None:
        self._get_or_create(persona_id, agent_name).record_round(round_number, opinion_text, score)

    def get(self, persona_id: str) -> Optional[OpinionState]:
        """Return the `OpinionState` for one agent, or `None` if untracked."""
        return self._states.get(persona_id)

    def all_states(self) -> list[OpinionState]:
        return list(self._states.values())

    def summary(self) -> dict[str, Any]:
        """Serialize every tracked agent's opinion history for persistence."""
        return {
            "topic": self.topic,
            "agents": {persona_id: state.to_dict() for persona_id, state in self._states.items()},
        }


